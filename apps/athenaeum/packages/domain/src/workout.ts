/**
 * The idempotent-import receipt (backend-internal collection, `workout-collections.ts`, plus the
 * `listWorkoutImports` read RPC, `workout-rpc.ts`) — one row per successfully imported `HKWorkout`,
 * keyed by `sourceWorkoutId` (the real `HKWorkout.uuid.uuidString`, or a synthetic source's own
 * stable id). Mirrors Enchiridion's own `workout_import_receipts` table
 * (`WorkoutModule.swift#importWorkout`: "Receipts are an optimisation, not the identity
 * authority... a durable page lets a restarted importer recover safely after a receipt is lost") —
 * same purpose here: a re-run import (the native client retrying after a dropped response, or a
 * user re-triggering a HealthKit sync) with the same `sourceWorkoutId` and the same content is a
 * cheap idempotent no-op (`ImportWorkoutOutput.duplicate: true`), not a duplicate node subgraph.
 *
 * `rootNodeId` is this receipt's one `linkedNodeId`-shaped field — a reference to the `Workout`-
 * tagged node this import created. See `workspace-durable-object.ts`'s `listWorkoutImports` doc
 * comment for why this field gets the same observer-exclusion treatment
 * `CalendarService#hiddenCalendarDerivedNodeIds` already established for `Meeting.linkedNodeId`/
 * `Bookmark.linkedNodeId`, even though nothing makes a workout-imported node hidden today.
 */
export class WorkoutImportReceipt extends Schema.Class<WorkoutImportReceipt>("WorkoutImportReceipt")({
  id: EntityId,
  workspaceId: EntityId,
  sourceWorkoutId: Schema.String.pipe(Schema.minLength(1)),
  source: WorkoutSource,
  payloadHash: Schema.String.pipe(Schema.minLength(1)),
  rootNodeId: EntityId,
  importedAt: IsoDateTimeString
}) {}

// --- Read models: listWorkouts/getWorkout (workout-rpc.ts) ----------------------------------
//
// Domain-extension task item 3's read side. Unlike `CalendarEvent`/`Bookmark`/`Meeting` (each a
// dedicated collection row `listWorkouts`/`getWorkout` could read directly), a Workout has no
// collection row of its own — per this file's header comment, and the plan's own Phase 7 framing
// ("HealthKit import as typed graph pages... no new mechanism"), a workout IS its `nodes`/`facts`/
// `edges` subgraph. These classes are therefore not storage rows but the assembled READ shape a
// `WorkoutsService` implementation (a later stage) reconstructs from `NodesRepository`/
// `GraphService` reads keyed off `WorkoutFactPredicate` — the reverse of `importWorkout`'s own
// `buildRootFacts`/`importWorkoutSubgraph` write path (`workouts-service-live.ts`).
//
// **`nodeId` gets the same observer-exclusion treatment as `WorkoutImportReceipt.rootNodeId`**
// (see that class's own doc comment): it is a `linkedNodeId`-shaped reference to a graph node, so
// a future `WorkoutsService#listWorkouts`/`#getWorkout` implementation MUST run its results
// through the same hidden-node filter `filterHiddenWorkoutImportReceipts`
// (`workspace-durable-object.ts`) already applies to `listWorkoutImports`, even though nothing makes
// a workout-imported node hidden today — the established defensive convention this codebase's
// hard constraints call for, not skipped just because this stage is schema-only.

/** One completed strength set, read back from a `Strength Set`-tagged node's facts
 *  (`WorkoutFactPredicate.Ordinal`/`.Repetitions`/`.LoadKilograms`/`.VolumeKilograms`/`.Rpe`/
 *  `.SetCompletedAt`). `nodeId` is that node's own id — present so a caller (a UI, or a future
 *  agent tool once workouts join that surface) can navigate to it directly via the existing
 *  generic graph RPCs, the same "read model points back at its source node" discipline
 *  `GetMeetingOutput`'s `Speaker`/`TranscriptSegmentRecord` rows establish for their own `id`
 *  fields (meeting-rpc.ts). */
export class WorkoutStrengthSet extends Schema.Class<WorkoutStrengthSet>("WorkoutStrengthSet")({
  nodeId: EntityId,
  ordinal: Schema.Number.pipe(Schema.int(), Schema.greaterThanOrEqualTo(1)),
  repetitions: Schema.Number.pipe(Schema.int(), Schema.nonNegative()),
  loadKilograms: Schema.Number.pipe(Schema.nonNegative()),
  volumeKilograms: Schema.Number.pipe(Schema.nonNegative()),
  rpe: Schema.optional(Schema.Number),
  completedAt: Schema.optional(IsoDateTimeString)
}) {}

/** One exercise within a strength workout, read back from a `Strength Exercise`-tagged node's
 *  facts plus its `sets` relation (`WorkoutRelationIds.ExerciseSets`), sets ordered by
 *  `WorkoutStrengthSet.ordinal`. */
export class WorkoutStrengthExercise extends Schema.Class<WorkoutStrengthExercise>("WorkoutStrengthExercise")({
  nodeId: EntityId,
  ordinal: Schema.Number.pipe(Schema.int(), Schema.greaterThanOrEqualTo(1)),
  name: Schema.String.pipe(Schema.minLength(1)),
  volumeKilograms: Schema.Number.pipe(Schema.nonNegative()),
  sets: Schema.Array(WorkoutStrengthSet)
}) {}

/** One distance/time split within a cardio workout, read back from a `Cardio Split`-tagged
 *  node's facts. May be an empty array on the owning `WorkoutDetail` when the source import had
 *  no lap/segment structure — see `CardioSplitImportInput`'s own doc comment (workout-rpc.ts) for
 *  why that is a common, expected case, not a data-loss bug. */
export class WorkoutCardioSplit extends Schema.Class<WorkoutCardioSplit>("WorkoutCardioSplit")({
  nodeId: EntityId,
  ordinal: Schema.Number.pipe(Schema.int(), Schema.greaterThanOrEqualTo(1)),
  distanceMeters: Schema.Number.pipe(Schema.greaterThan(0)),
  durationSeconds: Schema.Number.pipe(Schema.greaterThan(0)),
  paceSecondsPerKilometre: Schema.optional(Schema.Number),
  averageHeartRate: Schema.optional(Schema.Number),
  energyKilocalories: Schema.optional(Schema.Number)
}) {}

/** `GetWorkoutOutput`'s (workout-rpc.ts) discriminated child-subgraph payload — the read-side
 *  mirror of `WorkoutImportPayload` (workout-rpc.ts), same `kind`-discriminated shape and same
 *  rationale for discriminating on `kind` rather than deriving it from `activity` (see that
 *  type's own doc comment). */
export const WorkoutDetailPayload = Schema.Union(
  Schema.Struct({
    kind: Schema.Literal("strength"),
    exercises: Schema.Array(WorkoutStrengthExercise)
  }),
  Schema.Struct({
    kind: Schema.Literal("cardio"),
    splits: Schema.Array(WorkoutCardioSplit),
    distanceMeters: Schema.optional(Schema.Number),
    elevationMeters: Schema.optional(Schema.Number),
    averageSpeedMetersPerSecond: Schema.optional(Schema.Number),
    averagePaceSecondsPerKilometre: Schema.optional(Schema.Number)
  })
)
export type WorkoutDetailPayload = typeof WorkoutDetailPayload.Type

/** `listWorkouts`' (workout-rpc.ts) per-row shape — every root-node fact EXCEPT the strength/
 *  cardio roll-ups (`WorkoutFactPredicate.ExerciseCount`/`.TotalVolumeKilograms`/
 *  `.DistanceMeters`/etc.) and the child subgraph itself, matching `ListMeetingsOutput`'s
 *  identical "list is lightweight, get is the full aggregate" split (meeting-rpc.ts's own doc
 *  comment) — a workout-history list view needs only enough to render one row per workout, not
 *  every exercise/set/split; a caller wanting those calls `getWorkout`. `kind` says which of
 *  `Strength Workout`/`Cardio Workout` this root node is tagged (workout.ts's `WorkoutTagIds`)
 *  without the caller needing to inspect tags directly. */
export class WorkoutSummary extends Schema.Class<WorkoutSummary>("WorkoutSummary")({
  nodeId: EntityId,
  workspaceId: EntityId,
  sourceWorkoutId: Schema.String.pipe(Schema.minLength(1)),
  source: WorkoutSource,
  kind: Schema.Literal("strength", "cardio"),
  activity: WorkoutActivityKind,
  rawActivity: Schema.optional(Schema.String),
  startedAt: IsoDateTimeString,
  completedAt: IsoDateTimeString,
  durationSeconds: Schema.Number.pipe(Schema.nonNegative()),
  energyKilocalories: Schema.optional(Schema.Number),
  averageHeartRate: Schema.optional(Schema.Number),
  maximumHeartRate: Schema.optional(Schema.Number)
}) {}

/** `getWorkout`'s (workout-rpc.ts) full aggregate — every root-node fact plus the reconstructed
 *  exercise/set or split subgraph, mirroring `GetMeetingOutput`'s "one aggregate read, not
 *  several round trips" shape (meeting-rpc.ts's own doc comment). Deliberately NOT built by
 *  composing `WorkoutSummary` (e.g. `extends WorkoutSummary`'s fields) — this codebase's existing
 *  RPC files consistently declare each `Schema.Class`'s fields directly rather than compose
 *  schemas together (compare `StartMeetingOutput`/`GetMeetingOutput`, which share no base class
 *  despite both carrying a `Meeting`), so this follows the same flat-declaration convention
 *  rather than introducing a new composition pattern for one entity. */
export class WorkoutDetail extends Schema.Class<WorkoutDetail>("WorkoutDetail")({
  nodeId: EntityId,
  workspaceId: EntityId,
  sourceWorkoutId: Schema.String.pipe(Schema.minLength(1)),
  source: WorkoutSource,
  activity: WorkoutActivityKind,
  rawActivity: Schema.optional(Schema.String),
  startedAt: IsoDateTimeString,
  completedAt: IsoDateTimeString,
  durationSeconds: Schema.Number.pipe(Schema.nonNegative()),
  energyKilocalories: Schema.optional(Schema.Number),
  averageHeartRate: Schema.optional(Schema.Number),
  maximumHeartRate: Schema.optional(Schema.Number),
  payload: WorkoutDetailPayload
}) {}
