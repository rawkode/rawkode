// Phase 7 (plan §"Phased delivery": "Workouts + additional gatekeepers + optional blueprints...
// HealthKit import as typed graph pages (proves graph generality, no new mechanism)") — the
// domain shapes a native `HKWorkout` import maps onto. See `docs/workouts-decisions.md` for the
// full design rationale (HealthKit-data-model-mapping decision #1); this file only carries the
// resulting schemas/constants.
//
// **Why not `BASE_TAGS`** (task's decision point 1: "seeded per-workspace, or promoted to
// BASE_TAGS/builtin — decide and justify"): `tag.ts`'s 8 `BASE_TAGS` are a closed, cross-language-
// tested contract — `tag.test.ts#"has exactly 8 Base Tags"`, `graph-service.test.ts`, and the
// Swift↔TS fixture round trip (`EntityDecodingTests.swift#testBaseTagsFixtureMatchesPackageConstant`,
// generated by `native/AthenaeumDomain/scripts/generate-fixtures.ts`) all assert that exact count
// and set. `BASE_TAGS` are also, per the plan's own text, the universal entity vocabulary every
// workspace needs regardless of what it's used for (Person/Organization/Company/Event/Place/Area/
// Project/Task) — Workout/Strength/Cardio/Exercise/Set/Split is a single *feature's* vocabulary,
// named in the plan's Context section in a different sentence, not amended into that enumerated
// list. Widening `BASE_TAGS` to 14 would (a) break that tested invariant for every existing workspace
// and test fixture and (b) unconditionally clutter every workspace — including ones that never import
// a workout — with 6 rows it will never use, forever (Base Tags are seeded once, at workspace
// construction, for every workspace: `seed-base-tags.ts`).
//
// So: a **separate, parallel constant** (`WORKOUT_TAGS`/`WORKOUT_RELATION_DEFINITIONS`), with the
// identical "fixed nil-pattern UUID, `builtin: true`, ship with the app" shape `tag.ts`'s own
// header comment documents for `BASE_TAGS` — Enchiridion's own precedent for this *exact* tag set
// agrees: `WorkoutModule.manifest` (`apps/enchiridion/Sources/EnchiridionCore/WorkoutModule.swift`)
// marks every one of these six supertags `isBuiltIn: true` (preventing user rename/delete of a
// tag the import pipeline depends on referencing by fixed id) while keeping them in their own
// module manifest, entirely separate from Enchiridion's base entity tags — the same two-axis
// split (immutable, but not universal) this file makes. Seeded **lazily, idempotently, per-workspace**
// on first `importWorkout` call (`workouts-service-live.ts#ensureWorkoutTagsSeeded`), not
// unconditionally at workspace construction — a workspace that never imports a workout never gets these
// rows at all.
export const WorkoutTagIds = {
  Workout: EntityId.make("00000000-0000-0000-0000-000000000101"),
  StrengthWorkout: EntityId.make("00000000-0000-0000-0000-000000000102"),
  CardioWorkout: EntityId.make("00000000-0000-0000-0000-000000000103"),
  StrengthExercise: EntityId.make("00000000-0000-0000-0000-000000000104"),
  StrengthSet: EntityId.make("00000000-0000-0000-0000-000000000105"),
  CardioSplit: EntityId.make("00000000-0000-0000-0000-000000000106")
} as const

/**
 * The 6 fixed Workout tags, mirroring Enchiridion's own `WorkoutModule.manifest` supertag set
 * (`Workout`, `Strength Workout`, `Cardio Workout`, `Strength Exercise`, `Strength Set`,
 * `Cardio Split`) — see this file's header comment for why these are a parallel constant, not an
 * extension of `BASE_TAGS`.
 *
 * `Strength Workout`/`Cardio Workout` declare `Workout` as a DAG parent (`parentIds: [Workout]`)
 * — a node tagged `Strength Workout` is transitively `Workout` via `tagClosure`/`graph_tag_closure`
 * (tag-closure.ts), so `hasTag(Workout)` queries find every workout regardless of kind without the
 * import pipeline needing to assign both tags to one node (contrast with Enchiridion's own
 * `createWorkoutPage`, which DOES assign every field-owning supertag explicitly — necessary there
 * only because Enchiridion ties fields to their *exact* owning supertag; Athenaeum's `Fact` rows
 * (fact.ts) carry no such tag-ownership constraint, so a single leaf-tag assignment suffices here
 * — see `docs/workouts-decisions.md` for the full comparison).
 *
 * `Strength Exercise`/`Strength Set`/`Cardio Split` declare no parent — they are never queried via
 * `hasTag(Workout)` themselves (a Set is not itself a Workout), only reached via the `edges`
 * relations below.
 */
export const WORKOUT_TAGS: ReadonlyArray<Tag> = [
  new Tag({ id: WorkoutTagIds.Workout, name: "Workout", parentIds: [], builtin: true }),
  new Tag({
    id: WorkoutTagIds.StrengthWorkout,
    name: "Strength Workout",
    parentIds: [WorkoutTagIds.Workout],
    builtin: true
  }),
  new Tag({
    id: WorkoutTagIds.CardioWorkout,
    name: "Cardio Workout",
    parentIds: [WorkoutTagIds.Workout],
    builtin: true
  }),
  new Tag({ id: WorkoutTagIds.StrengthExercise, name: "Strength Exercise", parentIds: [], builtin: true }),
  new Tag({ id: WorkoutTagIds.StrengthSet, name: "Strength Set", parentIds: [], builtin: true }),
  new Tag({ id: WorkoutTagIds.CardioSplit, name: "Cardio Split", parentIds: [], builtin: true })
]

